class BotAction(BaseModel):
    """Per-tick synthetic controller command generated by the playtester bot."""
    deliberation: str = Field(
        default="",
        description="Epistemic rationale explaining the tactical movement and combat decision for this tick."
    )
    move_x: float = Field(default=0.0, description="Normalized horizontal movement axis (-1.0 to 1.0).")
    move_y: float = Field(default=0.0, description="Normalized vertical movement axis (-1.0 to 1.0).")
    aim_x: float = Field(default=0.0, description="Aim target X position in world coordinates.")
    aim_y: float = Field(default=0.0, description="Aim target Y position in world coordinates.")
    dash_pressed: bool = Field(default=False, description="Whether dash action is triggered.")
    fire_pressed: bool = Field(default=False, description="Whether weapon firing is triggered.")

    @property
    def move_vector(self) -> Vector2:
        return Vector2(self.move_x, self.move_y)

    @property
    def aim_vector(self) -> Vector2:
        return Vector2(self.aim_x, self.aim_y)

    @property
    def dash(self) -> bool:
        return self.dash_pressed

    @property
    def fire(self) -> bool:
        return self.fire_pressed

    def to_dict(self) -> Dict[str, Any]:
        return {
            "deliberation": self.deliberation,
            "move_x": self.move_x,
            "move_y": self.move_y,
            "aim_x": self.aim_x,
            "aim_y": self.aim_y,
            "dash_pressed": self.dash_pressed,
            "fire_pressed": self.fire_pressed,
        }


class PlaytestResult(BaseModel):
    """Formal verification report emitted by the Synthetic Playtesting Bot.
    Enforces strict Rationale-First Epistemic Architecture (deliberation declared first).
    """

class DualPlaytester:
    """Orchestrates dual playtesting runs across RusherBot and CautiousBot inside HeadlessSimulator."""
    deliberation: str = "Dual playtesting harness validating candidate level across contrasting archetypes."

    def __init__(self, tile_size: float = 32.0, max_ticks: int = 3600):
        self.tile_size = float(tile_size)
        self.max_ticks = int(max_ticks)
        self.rusher_bot = RusherBot(tile_size=tile_size)
        self.cautious_bot = CautiousBot(tile_size=tile_size)

    def evaluate_cartridge_dual(
        self,
        cartridge: BaseCartridge,
        episode_number: int = 1,
        ignore_combat_lock: bool = False,
    ) -> DualPlaytestReport:
        """Executes candidate cartridge under both RusherBot and CautiousBot and correlates findings."""
        from engine.sim.simulator import HeadlessSimulator

        # 1. Run RusherBot
        sim_rusher = HeadlessSimulator(
            cartridge=cartridge,
            episode_number=episode_number,
            ignore_combat_lock=ignore_combat_lock,
            max_steps=self.max_ticks,
        )
        rusher_res = self.rusher_bot.run_playtest(sim_rusher)
        if not getattr(rusher_res, "bot_name", None):
            rusher_res.bot_name = "RusherBot"

        # 2. Run CautiousBot
        sim_cautious = HeadlessSimulator(
            cartridge=cartridge,
            episode_number=episode_number,
            ignore_combat_lock=ignore_combat_lock,
            max_steps=self.max_ticks,
        )
        cautious_res = self.cautious_bot.run_playtest(sim_cautious)
        if not getattr(cautious_res, "bot_name", None):
            cautious_res.bot_name = "CautiousBot"

        # 3. Analyze divergence
        both_cleared = rusher_res.cleared and cautious_res.cleared
        pacing_div = abs(sim_rusher.stats.get("dashes", 0) - sim_cautious.stats.get("dashes", 0))

        status = "PROMOTED" if both_cleared else "REJECTED"
        failure_type = rusher_res.failure_type or cautious_res.failure_type

        delib = (
            f"Dual playtest evaluation complete: both_cleared={both_cleared}. "
            f"RusherBot: cleared={rusher_res.cleared}, time={rusher_res.completion_time_sec:.2f}s, dashes={sim_rusher.stats.get('dashes', 0)}. "
            f"CautiousBot: cleared={cautious_res.cleared}, time={cautious_res.completion_time_sec:.2f}s, dashes={sim_cautious.stats.get('dashes', 0)}. "
            f"Pacing divergence={pacing_div}. Final Status={status}."
        )

        return DualPlaytestReport(
            deliberation=delib,
            rusher_result=rusher_res,
            cautious_result=cautious_res,
            both_cleared=both_cleared,
            pacing_divergence=float(pacing_div),
            status=status,
            failure_type=failure_type,
            telemetry_summary={
                "rusher_stats": sim_rusher.stats,
                "cautious_stats": sim_cautious.stats,
            }
        )

